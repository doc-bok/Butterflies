package com.bokmcdok.butterflies.common.loot;

import com.bokmcdok.butterflies.registries.ItemRegistry;
import com.google.gson.JsonObject;

import java.util.List;
import java.util.Random;

import net.minecraft.resources.ResourceLocation;
import com.mojang.serialization.Codec;
import com.mojang.serialization.codecs.RecordCodecBuilder;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.level.storage.loot.LootContext;
import net.minecraft.world.level.storage.loot.predicates.LootItemCondition;
import net.minecraftforge.common.loot.GlobalLootModifierSerializer;
import org.jetbrains.annotations.NotNull;

import java.util.function.Supplier;

/**
 * A loot modifier to add treasure to some chests.
 */
public class TrailRuinsRareLootModifier extends BaseLootModifier {

    /**
     * Construction
     * @param conditionsIn The conditions needed for this loot modifier to apply.
     */
    public TrailRuinsRareLootModifier(LootItemCondition[] conditionsIn)
    {
        super(conditionsIn);
    }

    /**
     * Apply the modification to the loot.
     * @param generatedLoot the list of ItemStacks that will be dropped, generated by loot tables
     * @param context the LootContext, identical to what is passed to loot tables
     * @return The potentially updated loot.
     */
    @NotNull
    @Override
    public List<ItemStack> doApply(List<ItemStack> generatedLoot,
                                   LootContext context) {
        Random random = context.getRandom();

        // 1/13 chance to replace with new sherd.
        if (!generatedLoot.isEmpty() && random.nextInt(13) == 1) {
            generatedLoot.remove(0);

            ItemStack stack = new ItemStack(ItemRegistry.BUTTERFLY_POTTERY_SHERD.get());
            generatedLoot.add(stack);
        }

        return generatedLoot;
    }

    /**
     * The Loot Modifier Serializer.
     */
    public static class Serializer extends GlobalLootModifierSerializer<TrailRuinsRareLootModifier> {

        /**
         * Read Loot Modifier data.
         * @param name The resource name.
         * @param object The Json Object with any extra data.
         * @param conditionsIn The conditions for the loot.
         * @return A new loot modifier.
         */
        @Override
        public TrailRuinsRareLootModifier read(ResourceLocation name,
                                          JsonObject object,
                                          LootItemCondition[] conditionsIn) {
            return new TrailRuinsRareLootModifier(conditionsIn);
        }

        /**
         * Write loot modifier data.
         * @param instance The loot modifier.
         * @return Modifier data in JSON format.
         */
        @Override
        public JsonObject write(TrailRuinsRareLootModifier instance) {
            return makeConditions(instance.conditions);
        }
    }
}
